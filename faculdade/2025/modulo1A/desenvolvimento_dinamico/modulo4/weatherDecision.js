//As variáveis podem ser "rainy", "sunny" e "cloudy".

//variável que define a condição
let forecastWeather = "cloudy";

//Instrução e repetição.
if (forecastWeather === "rainy") {
  console.log("Devemos levar o guarda chuva!");
} else if (forecastWeather === "cloudy") {
  console.log("Dia nublado, levar o guarda chuva por precaução");
} else {
  console.log("Não devemos levar o guarda chuva!");
}
